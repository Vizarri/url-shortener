package com.rebuy.urlshortener.db.model;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.PrePersist;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.time.Instant;

/**
 * Persistent mapping between a case-sensitive public code and its original URL.
 * The generated database identifier is independent of the public short code.
 */
@Entity
@Table(name = "short_links")
@Getter
@NoArgsConstructor
public class ShortLink {

    /** Internal row identifier generated by PostgreSQL. */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /** Unique four-character Base62 code used in the public short URL. */
    @Setter
    @Column(name = "code", nullable = false, length = 4, updatable = false)
    private String code;

    /** Original destination URL, including its query parameters and fragment. */
    @Setter
    @Column(name = "target_url", nullable = false, columnDefinition = "text", updatable = false)
    private String targetUrl;

    /** Time at which the entity was first persisted. */
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    /** Initializes the creation timestamp before the first JPA insert. */
    @PrePersist
    void onCreate() {
        createdAt = Instant.now();
    }
}
